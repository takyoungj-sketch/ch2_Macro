export function formatPeriodRange(start: string | null | undefined, end: string | null | undefined): string {
  const fmt = (s: string) => s.replace(/-/g, ".");
  if (start && end) return `${fmt(start)}~${fmt(end)}`;
  if (end) return fmt(end);
  return "";
}
