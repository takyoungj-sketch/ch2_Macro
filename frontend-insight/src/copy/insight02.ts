export function formatAsOfMonth(raw: string | null | undefined): string {
  if (!raw) return "";
  const m = raw.match(/^(\d{4})-(\d{2})/);
  if (m) return `${m[1]}.${m[2]}`;
  return raw.replace(/-/g, ".");
}

export function shortType(name: string): string {
  return TYPE_SHORT[name] ?? name;
}

export function pairLabel(a: string, b: string): string {
  return `${a} × ${b}`;
}
